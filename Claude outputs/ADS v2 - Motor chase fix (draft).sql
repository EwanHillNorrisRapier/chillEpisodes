--  Send-date formats and fill rates per campaign. Home parses the send dates with a plain
--  try_cast(... as date); the Motor SaleDate is dd/mm/yyyy text. If the send dates are also
--  dd/mm/yyyy, the fallback parse in section 1 picks them up, but check before relying on it.
select  Campaign,
        count(*)                                                        as SnapshotRows,
        count(distinct PolicyCode)                                      as Policies,
        sum(case when Day1SendDate  is not null then 1 else 0 end)      as Day1Filled,
        sum(case when Day7SendDate  is not null then 1 else 0 end)      as Day7Filled,
        sum(case when Day14SendDate is not null then 1 else 0 end)      as Day14Filled,
        sum(case when Day20SendDate is not null then 1 else 0 end)      as Day20Filled,
        min(Day1SendDate)                                               as Day1Sample,
        min(Day20SendDate)                                              as Day20Sample
from    ods_v2.DocumentChaseMotorVan
where   PolicyTypeGroup = 'Motor'
and     PolicyType = 'New Business'
group by Campaign
order by Campaign;

--  Is the campaign's own send date the one to use on its row? Each row should carry its own
--  campaign's date (as the Home build assumes); a row whose own date is empty is lost below.
select  Campaign,
        sum(case when case Campaign when 'DAY 1'  then Day1SendDate  when 'DAY 7'  then Day7SendDate
                                    when 'DAY 14' then Day14SendDate when 'DAY 20' then Day20SendDate end is null
                 then 1 else 0 end)                                     as OwnSendDateMissing,
        count(*)                                                        as SnapshotRows
from    ods_v2.DocumentChaseMotorVan
where   PolicyTypeGroup = 'Motor'
and     PolicyType = 'New Business'
group by Campaign
order by Campaign;


