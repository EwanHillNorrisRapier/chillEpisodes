--  The habits list: count, first / last time per family, and how far each chase sits from the
--  sale. A send before the sale, or months after it, means the send date is not the one wanted.
select  e.EventTypeId,
        count(*)                                                        as Events,
        count(distinct e.SourcePolicyReference)                         as Policies,
        min(e.EventDateTime)                                            as FirstEvent,
        max(e.EventDateTime)                                            as LastEvent,
        sum(case when datediff(e.EventDate, s.SaleDate) < 0  then 1 else 0 end) as BeforeSale,
        percentile_approx(datediff(e.EventDate, s.SaleDate), 0.5)       as MedianDaysAfterSale,
        sum(case when datediff(e.EventDate, s.SaleDate) > 60 then 1 else 0 end) as Over60DaysAfterSale
from    ads_v2.EventStream e
left join (
        select  PolicyCode, min(SaleDate) as SaleDate
        from    stg.adsv2_motor_chase
        group by PolicyCode
        ) s     on s.PolicyCode = e.SourcePolicyReference
where   e.EventTypeId in ('A6', 'A6.F1', 'A6.B1.F1', 'A7.F1', 'A6.B1.1', 'A6.B1.4', 'A7.B1.4')
group by e.EventTypeId
order by e.EventTypeId;

